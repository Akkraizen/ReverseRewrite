from collections.abc import Collection
from typing import Protocol


class RecordNotFound(LookupError):
    pass


class Repository[ENTITY, ID](Protocol):
    async def find(self, id: ID, **filters: object) -> ENTITY | None: ...
    async def find_all(self, **filters: object) -> Collection[ENTITY]: ...
    async def insert(self, entity: ENTITY) -> ENTITY: ...
    async def update(self, entity: ENTITY) -> ENTITY | None: ...
    async def delete(self, id: ID, **filters: object) -> ENTITY | None: ...
    async def delete_all(self, **filters: object) -> Collection[ENTITY]: ...
    async def exists(self, id: ID, **filters: object) -> bool: ...
